// Helper to generate realistic intraday ticks matching open, high, low and closing price
function generateIntradayTicks(
  basePrice: number, 
  openPrice: number, 
  highPrice?: number, 
  lowPrice?: number
): IntradayTick[] {
  const ticks: IntradayTick[] = [];
  const maxP = highPrice ?? Math.max(basePrice, openPrice);
  const minP = lowPrice ?? Math.min(basePrice, openPrice);
  
  let currentPrice = openPrice;
  const startTime = 9 * 60; // 09:00
  const totalMinutes = 270; // until 13:30

  for (let i = 0; i <= totalMinutes; i += 15) {
    const hours = Math.floor((startTime + i) / 60);
    const mins = (startTime + i) % 60;
    const timeStr = `${String(hours).padStart(2, '0')}:${String(mins).padStart(2, '0')}`;
    
    // Controlled movement towards basePrice while staying within minP and maxP
    const progress = i / totalMinutes;
    const target = openPrice + (basePrice - openPrice) * progress;
    const noise = (Math.random() - 0.5) * (maxP - minP) * 0.25;
    currentPrice = Math.min(maxP, Math.max(minP, Number((target + noise).toFixed(2))));
    
    const vol = Math.floor(Math.random() * 450 + 80);
    const orderTypes: ('buy' | 'sell' | 'neutral')[] = ['buy', 'buy', 'sell', 'buy', 'neutral'];
    const chosenType = orderTypes[Math.floor(Math.random() * orderTypes.length)];
    
    ticks.push({
      time: timeStr,
      price: currentPrice,
      volume: vol,
      type: chosenType,
      orderSizeCategory: vol > 350 ? 'superLarge' : vol > 200 ? 'large' : vol > 100 ? 'medium' : 'small',
    });
  }
  // Ensure the last tick equals basePrice exactly (closing price at 13:30)
  if (ticks.length > 0) {
    ticks[ticks.length - 1].price = basePrice;
    ticks[0].price = openPrice;
  }
  return ticks;
}

